ALTER TABLE tb_plans
    ADD COLUMN IF NOT EXISTS is_active boolean,
    ADD COLUMN IF NOT EXISTS max_condominiums integer,
    ADD COLUMN IF NOT EXISTS max_users_per_condominium integer,
    ADD COLUMN IF NOT EXISTS monthly_price numeric(10,2),
    ADD COLUMN IF NOT EXISTS created_at timestamp(6),
    ADD COLUMN IF NOT EXISTS updated_at timestamp(6),
    ADD COLUMN IF NOT EXISTS name varchar(100);

CREATE TABLE IF NOT EXISTS tb_subscriptions (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    end_date date,
    start_date date NOT NULL,
    created_at timestamp(6) NOT NULL,
    plan_id bigint NOT NULL,
    updated_at timestamp(6) NOT NULL,
    status varchar(20) NOT NULL,
