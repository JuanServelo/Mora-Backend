-- =============================================================================
-- V1: estrutura inicial do ocorrencias-service (banco `mora_ocorrencias`)
--
-- Quem cria e evolui o banco é o Flyway; o Hibernate só confere
-- (`ddl-auto: validate`), como nos outros serviços Java.
--
-- O conteúdo é o esquema que o Hibernate gera para as entidades, lido do
-- catálogo do Postgres, com nomes legíveis nas constraints.
--
-- Idempotente (IF NOT EXISTS): o banco já existe em quem subiu o serviço antes
-- do Flyway. Lá esta versão só cria o que faltar e entra no histórico.
-- =============================================================================

-- Ocorrência registrada por um morador.
CREATE TABLE IF NOT EXISTS reclamacoes (
    id            bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    usuario_id    varchar(64)  NOT NULL,
    condominio_id varchar(50)  NOT NULL,
    protocolo     varchar(40)  NOT NULL,
    categoria     varchar(40)  NOT NULL,
    descricao     text         NOT NULL,
    anexo_url     varchar(500),
    status        varchar(20)  NOT NULL,
    criado_em     timestamp(6) NOT NULL,
    atualizado_em timestamp(6) NOT NULL,
    resolvido_em  timestamp(6),
    CONSTRAINT reclamacoes_pkey PRIMARY KEY (id),
    CONSTRAINT uq_reclamacoes_protocolo UNIQUE (protocolo),
    CONSTRAINT reclamacoes_status_check CHECK (status IN ('PENDENTE', 'EM_ANALISE', 'RESOLVIDO'))
);

-- Histórico de atendimento: resposta do síndico e mudança de status, com autor.
CREATE TABLE IF NOT EXISTS reclamacao_interacoes (
    id              bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    reclamacao_id   bigint       NOT NULL,
    autor_id        varchar(64),
    autor_email     varchar(255),
    autor_perfil    varchar(30),
    mensagem        text         NOT NULL,
    status_anterior varchar(20),
    status_novo     varchar(20),
    criado_em       timestamp(6) NOT NULL,
    CONSTRAINT reclamacao_interacoes_pkey PRIMARY KEY (id),
    CONSTRAINT fk_interacoes_reclamacao FOREIGN KEY (reclamacao_id) REFERENCES reclamacoes (id),
    CONSTRAINT reclamacao_interacoes_status_anterior_check CHECK (status_anterior IN ('PENDENTE', 'EM_ANALISE', 'RESOLVIDO')),
    CONSTRAINT reclamacao_interacoes_status_novo_check CHECK (status_novo IN ('PENDENTE', 'EM_ANALISE', 'RESOLVIDO'))
);

-- Prestadores de serviço. Não se excluem: desativam.
CREATE TABLE IF NOT EXISTS fornecedores (
    id            bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    condominio_id varchar(50)  NOT NULL,
    nome          varchar(150) NOT NULL,
    servico       varchar(100),
    telefone      varchar(20),
    email         varchar(150),
    documento     varchar(20),
    ativo         boolean      NOT NULL,
    criado_em     timestamp(6) NOT NULL,
    CONSTRAINT fornecedores_pkey PRIMARY KEY (id)
);

-- Ordem de serviço: nasce de uma ocorrência (reclamacao_id) ou preventiva (nulo).
CREATE TABLE IF NOT EXISTS ordens_servico (
    id               bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    condominio_id    varchar(50)   NOT NULL,
    numero           varchar(40)   NOT NULL,
    descricao        text          NOT NULL,
    prioridade       varchar(20)   NOT NULL,
    prazo            date          NOT NULL,
    responsavel      varchar(150)  NOT NULL,
    fornecedor_id    bigint,
    reclamacao_id    bigint,
    status           varchar(20)   NOT NULL,
    aberta_por_id    varchar(64)   NOT NULL,
    aberta_por_email varchar(255),
    custo            numeric(12,2),
    observacoes      text,
    concluida_em     timestamp(6),
    criado_em        timestamp(6)  NOT NULL,
    atualizado_em    timestamp(6)  NOT NULL,
    CONSTRAINT ordens_servico_pkey PRIMARY KEY (id),
    CONSTRAINT uq_ordens_servico_numero UNIQUE (numero),
    CONSTRAINT fk_ordens_servico_fornecedor FOREIGN KEY (fornecedor_id) REFERENCES fornecedores (id),
    CONSTRAINT fk_ordens_servico_reclamacao FOREIGN KEY (reclamacao_id) REFERENCES reclamacoes (id),
    CONSTRAINT ordens_servico_prioridade_check CHECK (prioridade IN ('BAIXA', 'MEDIA', 'ALTA', 'CRITICA')),
    CONSTRAINT ordens_servico_status_check CHECK (status IN ('ABERTA', 'EM_EXECUCAO', 'ATRASADA', 'CONCLUIDA')),
    -- Custo só faz sentido não negativo; a API já recusa, o banco garante.
    CONSTRAINT ordens_servico_custo_check CHECK (custo IS NULL OR custo >= 0)
);

-- Histórico da OS, com autor (nulo quando foi o sistema, como no job de atraso).
CREATE TABLE IF NOT EXISTS ordem_servico_andamentos (
    id               bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ordem_servico_id bigint       NOT NULL,
    autor_id         varchar(64),
    autor_email      varchar(255),
    mensagem         text         NOT NULL,
    status_anterior  varchar(20),
    status_novo      varchar(20),
    criado_em        timestamp(6) NOT NULL,
    CONSTRAINT ordem_servico_andamentos_pkey PRIMARY KEY (id),
    CONSTRAINT fk_andamentos_ordem_servico FOREIGN KEY (ordem_servico_id) REFERENCES ordens_servico (id),
    CONSTRAINT ordem_servico_andamentos_status_anterior_check CHECK (status_anterior IN ('ABERTA', 'EM_EXECUCAO', 'ATRASADA', 'CONCLUIDA')),
    CONSTRAINT ordem_servico_andamentos_status_novo_check CHECK (status_novo IN ('ABERTA', 'EM_EXECUCAO', 'ATRASADA', 'CONCLUIDA'))
);

-- Índices das consultas que as telas e os painéis fazem.
CREATE INDEX IF NOT EXISTS idx_reclamacoes_condominio ON reclamacoes (condominio_id, status);
CREATE INDEX IF NOT EXISTS idx_reclamacoes_usuario ON reclamacoes (usuario_id);
CREATE INDEX IF NOT EXISTS idx_reclamacao_interacoes_reclamacao ON reclamacao_interacoes (reclamacao_id);
CREATE INDEX IF NOT EXISTS idx_fornecedores_condominio ON fornecedores (condominio_id);
CREATE INDEX IF NOT EXISTS idx_ordens_servico_condominio ON ordens_servico (condominio_id, status);
CREATE INDEX IF NOT EXISTS idx_ordens_servico_reclamacao ON ordens_servico (reclamacao_id);
-- O job diário procura as OS em aberto com prazo vencido.
CREATE INDEX IF NOT EXISTS idx_ordens_servico_prazo ON ordens_servico (status, prazo);
CREATE INDEX IF NOT EXISTS idx_os_andamentos_ordem ON ordem_servico_andamentos (ordem_servico_id);
